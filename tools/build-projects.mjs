/**
 * build-projects.mjs — regenerate the cards on the projects page.
 *
 * The previous page was hand-maintained and listed two projects out of
 * thirty-five, which is the whole argument for this file existing: anything a
 * script can keep true, a script should keep true. The prose in
 * content/projects.js stays hand-written, because "why was this hard" is the
 * only part worth reading and no script can write it.
 *
 * Facts come from the repos themselves — the sibling directories in the
 * workspace — so they are read from the same place the work happens rather
 * than transcribed and left to drift.
 *
 *   node tools/build-projects.mjs            # rewrite the marked region
 *   node tools/build-projects.mjs --check    # fail if it would change anything
 *
 * --check is for the case where someone edits the page by hand and wonders why
 * it reverts: it tells them before they are surprised.
 *
 * Only the region between the PROJECTS markers is touched, so the nav, footer,
 * lizard and rat are all left exactly alone.
 */

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const HERE = dirname(fileURLToPath(import.meta.url));
const SITE = resolve(HERE, '..');
const WORKSPACE = resolve(SITE, '..');            // octopus-tentacles/
const PAGE = join(SITE, 'public', 'projects.html');

const START = '<!-- PROJECTS:START — generated by tools/build-projects.mjs, do not edit by hand -->';
const END   = '<!-- PROJECTS:END -->';

const projects = require(join(SITE, 'content', 'projects.js'));

// ── Facts ─────────────────────────────────────────────────────────────────────

// Extension → display name. Deliberately a small list: a language that is not
// here simply does not appear, which is a better failure than mislabelling a
// project by whatever happened to be in a config directory.
const LANGS = {
  '.ts': 'TypeScript', '.tsx': 'TypeScript',
  '.js': 'JavaScript', '.mjs': 'JavaScript', '.jsx': 'JavaScript',
  '.py': 'Python', '.rs': 'Rust', '.go': 'Go', '.nix': 'Nix',
  '.sh': 'Shell', '.sql': 'SQL', '.css': 'CSS', '.html': 'HTML',
  '.lua': 'Lua', '.java': 'Java', '.kt': 'Kotlin',
};

const SKIP_DIRS = new Set([
  'node_modules', '.git', 'dist', 'build', 'target', '.next',
  'vendor', '__pycache__', 'venv', '.venv', 'coverage',
]);

/** Bytes of source per language, so the labels reflect the actual bulk. */
function languagesOf(repoDir) {
  const bytes = new Map();
  const walk = (dir, depth = 0) => {
    if (depth > 6) return;
    let entries;
    try { entries = readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const e of entries) {
      if (e.name.startsWith('.') && e.name !== '.github') continue;
      const full = join(dir, e.name);
      if (e.isDirectory()) {
        if (SKIP_DIRS.has(e.name)) continue;
        walk(full, depth + 1);
      } else {
        const ext = e.name.slice(e.name.lastIndexOf('.'));
        const lang = LANGS[ext];
        if (!lang) continue;
        try { bytes.set(lang, (bytes.get(lang) || 0) + statSync(full).size); } catch { /* vanished */ }
      }
    }
  };
  walk(repoDir);

  const total = [...bytes.values()].reduce((a, b) => a + b, 0);
  if (!total) return [];
  return [...bytes.entries()]
    .filter(([, n]) => n / total >= 0.05)   // ignore a stray config file
    .sort((a, b) => b[1] - a[1])
    .slice(0, 4)
    .map(([lang]) => lang);
}

function git(repoDir, args) {
  try {
    return execFileSync('git', args, { cwd: repoDir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch { return ''; }
}

function lastUpdated(repoDir) {
  const iso = git(repoDir, ['log', '-1', '--format=%cI']);
  if (!iso) return null;
  const then = new Date(iso);
  const days = Math.floor((Date.now() - then.getTime()) / 86400000);
  if (days <= 0)  return 'today';
  if (days === 1) return 'yesterday';
  if (days < 30)  return `${days} days ago`;
  if (days < 365) return `${Math.round(days / 30)} months ago`;
  return `${Math.round(days / 365)} years ago`;
}

function commitCount(repoDir) {
  const n = git(repoDir, ['rev-list', '--count', 'HEAD']);
  return /^\d+$/.test(n) ? Number(n) : null;
}

/** Tests, when the repo has a suite worth counting. */
function testCount(repoDir) {
  const dir = join(repoDir, 'test');
  if (!existsSync(dir)) return null;
  let n = 0;
  for (const f of readdirSync(dir)) {
    if (!/\.test\.(js|mjs|ts)$/.test(f)) continue;
    const src = readFileSync(join(dir, f), 'utf8');
    n += (src.match(/^\s*test\(/gm) || []).length;
  }
  return n || null;
}

function factsFor(project) {
  if (!project.repo) return { languages: [], updated: null, commits: null, tests: null };
  const dir = join(WORKSPACE, project.repo);
  if (!existsSync(dir)) {
    console.warn(`  ! ${project.name}: no repo at ${dir} — facts skipped`);
    return { languages: [], updated: null, commits: null, tests: null };
  }
  return {
    languages: languagesOf(dir),
    updated: lastUpdated(dir),
    commits: commitCount(dir),
    tests: testCount(dir),
  };
}

// ── Rendering ─────────────────────────────────────────────────────────────────

const esc = s => String(s ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;')
  .replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// Blank lines in `detail` are paragraph breaks.
const paragraphs = text => String(text || '')
  .split(/\n\s*\n/).map(p => `<p>${esc(p.trim())}</p>`).join('\n            ');

function card(project) {
  const f = factsFor(project);

  const meta = [
    f.updated ? `updated ${f.updated}` : null,
    f.commits ? `${f.commits} commits` : null,
    f.tests   ? `${f.tests} tests` : null,
  ].filter(Boolean);

  return `        <article class="project-card project-card-wide">
          <h3>${esc(project.name)}</h3>
          <p class="card-blurb">${esc(project.blurb)}</p>
          <div class="card-detail">
            ${paragraphs(project.detail)}
          </div>
${project.highlights?.length ? `          <ul class="card-highlights">
${project.highlights.map(h => `            <li>${esc(h)}</li>`).join('\n')}
          </ul>\n` : ''}${f.languages.length ? `          <div class="languages">
${f.languages.map(l => `            <span>${esc(l)}</span>`).join('\n')}
          </div>\n` : ''}${meta.length ? `          <p class="card-meta">${esc(meta.join(' · '))}</p>\n` : ''}${project.url ? `          <a href="${esc(project.url)}" class="repo-link">See more on GitHub</a>\n` : ''}        </article>`;
}

console.log(`Building ${projects.length} project cards…`);
const cards = projects.map(card).join('\n');
const block = `${START}
      <div class="project-cards">
${cards}
      </div>
      ${END}`;

const page = readFileSync(PAGE, 'utf8');
const i = page.indexOf(START);
const j = page.indexOf(END);
if (i === -1 || j === -1) {
  console.error(`Markers not found in ${PAGE}.\nAdd these around the cards:\n  ${START}\n  ${END}`);
  process.exit(1);
}

const next = page.slice(0, i) + block + page.slice(j + END.length);

if (process.argv.includes('--check')) {
  if (next !== page) {
    console.error('projects.html is out of date — run: node tools/build-projects.mjs');
    process.exit(1);
  }
  console.log('projects.html is up to date.');
  process.exit(0);
}

writeFileSync(PAGE, next);
console.log(`Wrote ${PAGE}`);
